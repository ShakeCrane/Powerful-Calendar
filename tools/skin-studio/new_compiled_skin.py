#!/usr/bin/env python3
"""Create an audited, source-compiled PowerCal skin without editing core or the App host."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
APP_SKINS = HERE.parents[1] / "app/src/main/java/dev/powerfulcalendar/ui/v2/skins"
ID = re.compile(r"[a-z](?:[a-z0-9]|-(?=[a-z0-9])){2,31}\Z")
REGISTRY = APP_SKINS / "ActiveVisualSkin.kt"
MARKER = "            else -> PresentationSkinRegistry.reset() // invalid config always falls back"
PROFILES = [
    ("Timeline", "CompiledTimelineSkin", "TimelineSkinContext", "CompiledSkinRuntime.registerTimeline",
     "rendererId"),
    ("Month", "MonthVisualRenderer", "MonthVisualContext", "PresentationSkinRegistry.useMonth", "id"),
    ("Memo", "MemoVisualRenderer", "MemoVisualContext", "PresentationSkinRegistry.useMemo", "id"),
    ("Ai", "AiVisualRenderer", "AiVisualContext", "PresentationSkinRegistry.useAi", "id"),
    ("Settings", "SettingsVisualRenderer", "SettingsVisualContext", "PresentationSkinRegistry.useSettings", "id"),
    ("Navigation", "NavigationVisualRenderer", "NavigationVisualContext",
     "PresentationSkinRegistry.useNavigation", "id"),
    ("Deck", "DeckVisualRenderer", "DeckVisualContext", "DeckPresentationSkinRegistry.use", "id"),
    ("Overlay", "OverlayVisualRenderer", "OverlayVisualContext",
     "PresentationSkinRegistry.useOverlay", "id"),
    ("Picker", "PickerVisualRenderer", "PickerVisualContext",
     "PresentationSkinRegistry.usePicker", "id"),
    ("Chrome", "ChromeVisualRenderer", "ChromeVisualContext",
     "PresentationSkinRegistry.useChrome", "id"),
]


def stem(name: str) -> str:
    if not ID.fullmatch(name):
        raise ValueError("Skin ID must be lowercase 3–32 chars [a-z][a-z0-9-], e.g. aurora-glass")
    return "".join(word.capitalize() for word in name.split("-"))


def make_kotlin(name: str) -> str:
    klass = stem(name)
    registrations = "\n".join(
        "        " + registrar + "(" + klass + screen + "())"
        for screen, _, _, registrar, _ in PROFILES
    )
    classes = []
    for screen, interface, context, _, id_prop in PROFILES:
        classes.append(
            "private class " + klass + screen + " : " + interface + " {\n" +
            "    override val " + id_prop + " = " + json.dumps(name + "/" + screen.lower()) + "\n" +
            "    " + ("" if screen == "Picker" else "@Composable ") + "override fun Render(context: " + context + ") {\n" +
            "        // This fallback is deliberately complete and non-destructive.\n" +
            "        // Replace with your own Compose layout; call only context.on* actions.\n" +
            "        context.Native()\n" +
            "    }\n" +
            "}\n"
        )
    return (
        "package dev.powerfulcalendar.ui.v2\n\n"
        "import androidx.compose.runtime.Composable\n\n"
        "/** Generated by tools/skin-studio/new_compiled_skin.py. Edit ONLY presentation code. */\n"
        "internal object " + klass + "Skin {\n"
        "    fun install() {\n"
        "        PresentationSkinRegistry.reset()\n" +
        registrations + "\n"
        "    }\n"
        "}\n\n" +
        "\n".join(classes)
    )


def design_brief(name: str, document: dict) -> str:
    if document.get("format") != "powercal-skin-studio" or document.get("schemaVersion") != 1:
        raise ValueError("Expected a .pcstudio.json document (Studio schema 1)")
    pages = document.get("compiled", {}).get("pages", {})
    if not isinstance(pages, dict):
        raise ValueError("Missing compiled.pages")
    lines = [
        "# " + name + " visual design brief",
        "",
        "This is an authoring reference, NOT executable Android layout.",
        "Update the generated Compose renderers to implement each requested arrangement/motion.",
        "No layout claims are made from merely generating this file.",
        "",
    ]
    for page, slots in pages.items():
        if not isinstance(slots, list):
            raise ValueError("Invalid design page: " + str(page))
        lines.append("## " + str(page))
        for item in slots:
            if not isinstance(item, dict):
                raise ValueError("Malformed design slot")
            lines.append("- " + str(item.get("id", "")) +
                         " | zone=" + str(item.get("zone", "content")) +
                         " | motion=" + str(item.get("motion", "none")) +
                         " | duration=" + str(item.get("duration", 0)) +
                         "ms | visible=" + str(item.get("visible", True)))
        lines.append("")
    lines += [
        "## Required verification",
        "Do not claim this blueprint is implemented until the Kotlin classes reproduce it.",
        "Check the host action semantics, accessibility, reduced motion and exact time geometry.",
        "See docs/SKIN_AUTHORING_HANDBOOK.md and docs/UI_SKIN_EXTENSION_CONTRACT_V4.md.",
    ]
    return "\n".join(lines) + "\n"


def create(name: str, source_root: Path = APP_SKINS,
           activate: bool = False, design: Path | None = None) -> list[Path]:
    klass = stem(name)
    target = source_root / (klass + "Skin.kt")
    registry = source_root / "ActiveVisualSkin.kt"
    if target.exists():
        raise FileExistsError(str(target) + " already exists; no files changed")
    content = make_kotlin(name)
    brief_path = source_root / (klass + "DESIGN_BRIEF.md")
    brief_content = None
    if design is not None:
        if brief_path.exists():
            raise FileExistsError(str(brief_path) + " already exists")
        if design.stat().st_size > 24_000_000:
            raise ValueError("Studio design document exceeds 24MB")
        brief_content = design_brief(name, json.loads(design.read_text("utf-8")))
    updated = None
    if activate:
        src = registry.read_text("utf-8")
        if src.count(MARKER) != 1:
            raise ValueError("Activation marker mismatch; abort before writing")
        if "const val PROFILE = \"native\"" not in src:
            raise ValueError("Expected native profile before activation")
        new_case = "            " + json.dumps(name) + " -> " + klass + "Skin.install()\n"
        updated = src.replace(MARKER, new_case + MARKER)
        updated = updated.replace('const val PROFILE = "native"',
                                  "const val PROFILE = " + json.dumps(name))
    source_root.mkdir(parents=True, exist_ok=True)
    created = []
    try:
        target.write_text(content, encoding="utf-8")
        created.append(target)
        if brief_content is not None:
            brief_path.write_text(brief_content, encoding="utf-8")
            created.append(brief_path)
        if updated is not None:
            temp = registry.with_suffix(".kt.tmp")
            temp.write_text(updated, encoding="utf-8")
            temp.replace(registry)
            created.append(registry)
    except Exception:
        # If registration fails, generated files should never appear partially installed.
        for path in created:
            if path != registry:
                path.unlink(missing_ok=True)
        raise
    return created


def main():
    parser = argparse.ArgumentParser(description="Generate a source-compiled full-screen PowerCal skin")
    parser.add_argument("name", help="e.g. aurora-glass")
    parser.add_argument("--activate", action="store_true",
                        help="switch ActiveVisualSkin PROFILE from native to the new skin")
    parser.add_argument("--design", type=Path, help="optional .pcstudio.json as a design brief")
    args = parser.parse_args()
    for path in create(args.name, activate=args.activate, design=args.design):
        print(path)
    print("Then implement the 10 Render(context) methods and run Android build/tests.")


if __name__ == "__main__":
    main()
